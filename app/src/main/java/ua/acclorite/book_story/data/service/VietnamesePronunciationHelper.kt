    /**
     * Precompiled regex for whole-word replacement using word boundaries (\b).
     * Keys are sorted by descending length so compound terms (e.g. 'dependency injection', 'William Shakespeare')
     * match before shorter individual words ('injection', 'Shakespeare').
     */
    private val PRONUNCIATION_REGEX: Regex = Regex(
        "\\b(" + PRONUNCIATION_MAP.keys
            .sortedByDescending { it.length }
            .joinToString("|") { Regex.escape(it) } + ")\\b",
        RegexOption.IGNORE_CASE
    )

    /**
     * Replaces common English terms, specialized IT vocabulary, and foreign famous names in the given text
     * with their Vietnamese phonetic equivalents. Single-pass regex replacement in O(N).
     */
    fun applyReplacements(text: String): String {
        return PRONUNCIATION_REGEX.replace(text) { match ->
            val key = match.value.lowercase()
            PRONUNCIATION_MAP[key] ?: match.value
        }
    }
